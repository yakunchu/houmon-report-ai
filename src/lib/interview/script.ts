/**
 * 訪問時の想定問答集（読み上げ用の台本）。2026-11-07 社長の提案。
 *
 * ねらい: 質問をこの順番でして、相手の答えを薬剤師が**オウム返し**で自分の声で言う。
 * 録音には薬剤師の声だけ入ればよいので、インカムやピンマイクで自分の声を拾い、iPhone はカバンの中で録音していてよい。
 * 同じ順番・同じ言い回しで言うことで、担当者が違っても報告書の下書きが同じ形になる。
 *
 * - 文言は報告書の欄（docs/UI-V2.md ではなく CLAUDE.md「報告書の欄」）と、下書きルール（prompts/report-rules.md）の読み取り方に合わせてある。
 * - 数字は単位つきで言う。人の名前・施設名は言わず、続柄（娘さん、奥さん）で言う。分からないことは「未確認」と言う（下書きは「要確認」になる）。
 * - すべて架空の例文。実在の人物とは関係ない。
 */

export type InterviewStep = {
  /** 読み上げの順番（1 から） */
  no: number;
  /** 見出し */
  title: string;
  /** 対応する報告書の欄 */
  fields: readonly string[];
  /** 薬剤師が相手に聞く言葉 */
  ask: string;
  /** 相手の答えを受けて、薬剤師が自分の声で言う型（◯ に数や言葉を入れる） */
  echo: readonly string[];
  /** 架空の例（山本花子さんの台本に合わせた言い方） */
  example: string;
  /** 言い方の注意 */
  tip?: string;
};

